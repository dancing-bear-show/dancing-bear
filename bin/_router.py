#!/usr/bin/env python3
"""Execution router for dancing-bear bin/ wrappers.

This script is the single real file behind all generated wrappers.  Each
generated wrapper is a symlink to this script.  The router derives which
module to run from the name used to invoke it (sys.argv[0]).

Do not invoke this script directly — use the named wrappers (bin/mail,
bin/assistant, etc.).  The mapping from name to module is embedded below in
_MODULE_MAP, generated by bin/_gen_wrappers.py from bin/_wrappers.yaml.

Run `make bin-wrappers` to regenerate after changing _wrappers.yaml.
"""
from __future__ import annotations

import importlib.util
import os
import sys
from pathlib import Path

# Re-exec under the repo .venv interpreter when available.
# The system python3 (e.g. Homebrew Python 3.14) may lack required deps such
# as PyYAML.  Running under .venv guarantees the right interpreter and packages.
# Guard: skip if a venv is already active, or if we are already the venv python.
#
# The sentinel _DANCING_BEAR_VENV_EXEC stores the realpath of the venv python
# that this process exec'd into (not just "1").  A child wrapper for a different
# repo/venv, or one that genuinely needs a different interpreter, will not see
# its own venv python path here and will still re-exec correctly.  The only case
# that skips re-exec is when the sentinel equals THIS wrapper's venv python path,
# which means we already exec'd into the right interpreter and must not loop.
#
# __file__ resolves to the router's real path (symlinks are followed by
# Path.resolve()), so _REPO_ROOT is always the real repo root regardless of
# which symlink was used to invoke the router.
_REPO_ROOT = Path(__file__).resolve().parents[1]

# Load bin/_pathrepair.py by explicit filesystem path, NOT by `import`.
#
# That module carries the repair below and is shared with bin/llm and
# bin/path-guard, so the logic exists once rather than in three divergent
# copies. It cannot be imported normally: its whole job is to fix a broken
# import path, so a plain `import` would either fail or -- far worse --
# silently load a FOREIGN checkout's copy of itself and repair nothing. For
# the same reason it cannot live under src/, which is exactly what is not yet
# importable at this point.
_spec = importlib.util.spec_from_file_location(
    "_dancing_bear_pathrepair", _REPO_ROOT / "bin" / "_pathrepair.py"
)
if _spec is None or _spec.loader is None:  # pragma: no cover - defensive
    raise SystemExit("_router.py: cannot load bin/_pathrepair.py")
_pathrepair = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_pathrepair)

# Must run BEFORE the .venv re-exec below so the corrected PYTHONPATH is
# inherited across os.execv.
_pathrepair.strip_foreign_src_paths(_REPO_ROOT)

_VENV_PY = _REPO_ROOT / ".venv" / "bin" / "python3"
_VENV_PY_REAL = os.path.realpath(str(_VENV_PY)) if _VENV_PY.exists() else ""
if (
    _VENV_PY.exists()
    and sys.prefix == sys.base_prefix  # no venv active
    and os.path.realpath(sys.executable) != _VENV_PY_REAL
    and os.environ.get("_DANCING_BEAR_VENV_EXEC") != _VENV_PY_REAL
):
    os.environ["_DANCING_BEAR_VENV_EXEC"] = _VENV_PY_REAL
    # nosec B606 - not a shell-less process launch risk: _VENV_PY is a fixed
    # path derived from __file__ (the repo's own .venv/bin/python3), never from
    # user input, and argv is forwarded unchanged to that interpreter. This
    # exec existed in every generated wrapper before the router; it is newly
    # reported only because _router.py carries a .py extension that brings it
    # into bandit's scope.
    os.execv(str(_VENV_PY), [str(_VENV_PY)] + sys.argv)  # nosec B606

# After the re-exec, immediately before the first repo import: force our src/
# to the FRONT of sys.path. A membership test is not enough -- if our src/ is on
# the path but sits behind another checkout's, that one wins and the guard is a
# no-op.
# Called for its side effect; the returned path is not needed here.
_pathrepair.force_own_src_first(_REPO_ROOT)

# --- BEGIN GENERATED SECTION (bin/_gen_wrappers.py) ---
# fmt: off
_MODULE_MAP: dict[str, str] = {
    "mail": "mail",
    "phone": "phone",
    "calendar": "calendars",
    "schedule": "schedule",
    "whatsapp": "whatsapp",
    "wifi": "wifi",
    "slides": "slides",
    "sheets": "sheets",
    "maker": "maker",
    "assistant": "core.assistant_cli",
    "charts": "charts",
    "apple-music-assistant": "apple_music",
    "apple-music-user-token": "apple_music.user_token_cli",
    "diagrams": "diagrams",
    "telemetry": "telemetry.cli",
    "worker": "worker.cli",
    "workflow": "workflow.cli",
    "qlty-assistant": "qlty",
    "mail-assistant": "mail",
    "phone-assistant": "phone",
    "calendar-assistant": "calendars",
    "schedule-assistant": "schedule",
    "wifi-assistant": "wifi",
}
# fmt: on
# --- END GENERATED SECTION ---


def _main() -> int:
    """Dispatch to the correct module based on the invoked name."""
    invoked_as = os.path.basename(sys.argv[0])
    module = _MODULE_MAP.get(invoked_as)
    if module is None:
        sys.stderr.write(
            f"_router.py: unknown wrapper name {invoked_as!r}. "
            "Did you add a new entry to _wrappers.yaml and run `make bin-wrappers`?\n"
        )
        return 1

    if "." in module:
        # Dotted module: from {module} import main
        # e.g. core.assistant_cli -> from core.assistant_cli import main
        mod = __import__(module, fromlist=["main"])
        main_fn = getattr(mod, "main")
    else:
        # Package: from {module}.__main__ import main
        # e.g. mail -> from mail.__main__ import main
        mod = __import__(f"{module}.__main__", fromlist=["main"])
        main_fn = getattr(mod, "main")

    return main_fn()


if __name__ == "__main__":
    raise SystemExit(_main())
