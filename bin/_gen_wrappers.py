#!/usr/bin/env python3
"""Generate bin/ wrappers from _wrappers.yaml.

Usage:
    python3 bin/_gen_wrappers.py [--check] [--verbose]

Options:
    --check    Dry-run: report what would change without writing
    --verbose  Show all files, not just changes

Generated wrappers are symlinks to bin/_router.py.  The router derives which
module to run from sys.argv[0] (the symlink name), using a baked _MODULE_MAP
written into it by this script.  Run `make bin-wrappers` to regenerate after
changing _wrappers.yaml.

This script also keeps the wrapper-symlink exclusions in .qlty/qlty.toml in
sync, so qlty does not report the router's body once per symlink that points
at it.  See the generated block in that file for the full rationale.
"""
from __future__ import annotations

import argparse
import stat
import sys
from pathlib import Path

# Lazy import PyYAML (optional dep)
try:
    import yaml
except ImportError:
    yaml = None  # type: ignore[assignment]

BIN_DIR = Path(__file__).resolve().parent
CONFIG_FILE = BIN_DIR / "_wrappers.yaml"
ROUTER_FILE = BIN_DIR / "_router.py"
QLTY_CONFIG = BIN_DIR.parent / ".qlty" / "qlty.toml"

# Template for the bash wrappers (unchanged from original).
BASH_TEMPLATE = """\
#!/usr/bin/env bash
set -euo pipefail
SCRIPT_DIR="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
exec "$SCRIPT_DIR/{base}" {args} "$@"
"""

# Router template: the generated _MODULE_MAP section is injected between the
# BEGIN/END markers.  Everything outside the markers is static.
_ROUTER_TEMPLATE = '''\
#!/usr/bin/env python3
"""Execution router for dancing-bear bin/ wrappers.

This script is the single real file behind all generated wrappers.  Each
generated wrapper is a symlink to this script.  The router derives which
module to run from the name used to invoke it (sys.argv[0]).

Do not invoke this script directly — use the named wrappers (bin/mail,
bin/assistant, etc.).  The mapping from name to module is embedded below in
_MODULE_MAP, generated by bin/_gen_wrappers.py from bin/_wrappers.yaml.

Run `make bin-wrappers` to regenerate after changing _wrappers.yaml.
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

# Re-exec under the repo .venv interpreter when available.
# The system python3 (e.g. Homebrew Python 3.14) may lack required deps such
# as PyYAML.  Running under .venv guarantees the right interpreter and packages.
# Guard: skip if a venv is already active, or if we are already the venv python.
#
# The sentinel _DANCING_BEAR_VENV_EXEC stores the realpath of the venv python
# that this process exec'd into (not just "1").  A child wrapper for a different
# repo/venv, or one that genuinely needs a different interpreter, will not see
# its own venv python path here and will still re-exec correctly.  The only case
# that skips re-exec is when the sentinel equals THIS wrapper\'s venv python path,
# which means we already exec\'d into the right interpreter and must not loop.
#
# __file__ resolves to the router\'s real path (symlinks are followed by
# Path.resolve()), so _REPO_ROOT is always the real repo root regardless of
# which symlink was used to invoke the router.
_REPO_ROOT = Path(__file__).resolve().parents[1]
_VENV_PY = _REPO_ROOT / ".venv" / "bin" / "python3"
_VENV_PY_REAL = os.path.realpath(str(_VENV_PY)) if _VENV_PY.exists() else ""
if (
    _VENV_PY.exists()
    and sys.prefix == sys.base_prefix  # no venv active
    and os.path.realpath(sys.executable) != _VENV_PY_REAL
    and os.environ.get("_DANCING_BEAR_VENV_EXEC") != _VENV_PY_REAL
):
    os.environ["_DANCING_BEAR_VENV_EXEC"] = _VENV_PY_REAL
    # nosec B606 - not a shell-less process launch risk: _VENV_PY is a fixed
    # path derived from __file__ (the repo's own .venv/bin/python3), never from
    # user input, and argv is forwarded unchanged to that interpreter. This
    # exec existed in every generated wrapper before the router; it is newly
    # reported only because _router.py carries a .py extension that brings it
    # into bandit's scope.
    os.execv(str(_VENV_PY), [str(_VENV_PY)] + sys.argv)  # nosec B606

SRC_ROOT = _REPO_ROOT / "src"
if str(SRC_ROOT) not in sys.path:
    sys.path.insert(0, str(SRC_ROOT))

{generated_section}


def _main() -> int:
    """Dispatch to the correct module based on the invoked name."""
    invoked_as = os.path.basename(sys.argv[0])
    module = _MODULE_MAP.get(invoked_as)
    if module is None:
        sys.stderr.write(
            f"_router.py: unknown wrapper name {{invoked_as!r}}. "
            "Did you add a new entry to _wrappers.yaml and run `make bin-wrappers`?\\n"
        )
        return 1

    if "." in module:
        # Dotted module: from {{module}} import main
        # e.g. core.assistant_cli -> from core.assistant_cli import main
        mod = __import__(module, fromlist=["main"])
        main_fn = getattr(mod, "main")
    else:
        # Package: from {{module}}.__main__ import main
        # e.g. mail -> from mail.__main__ import main
        mod = __import__(f"{{module}}.__main__", fromlist=["main"])
        main_fn = getattr(mod, "main")

    return main_fn()  # type: ignore[no-any-return]


if __name__ == "__main__":
    raise SystemExit(_main())
'''

_GENERATED_SECTION_HEADER = "# --- BEGIN GENERATED SECTION (bin/_gen_wrappers.py) ---"
_GENERATED_SECTION_FOOTER = "# --- END GENERATED SECTION ---"

# Markers delimiting the generated wrapper-symlink block inside
# .qlty/qlty.toml's exclude_patterns list.
_QLTY_SECTION_HEADER = "  # --- BEGIN GENERATED WRAPPER SYMLINKS (bin/_gen_wrappers.py) ---"
_QLTY_SECTION_FOOTER = "  # --- END GENERATED WRAPPER SYMLINKS ---"

_QLTY_SECTION_COMMENT = """\
  # Every bin/<name> below is a SYMLINK to bin/_router.py, which is the single
  # real file behind all generated wrappers. qlty follows each symlink and reads
  # the same 115 lines once per name, then reports them as N clones of each
  # other -- one identical-code finding per wrapper, all pointing at the one
  # file. That is an artifact of symlink traversal, not duplicated source: git
  # stores these as mode 120000 pointing at a single blob.
  #
  # Only the symlink NAMES are excluded. bin/_router.py itself is deliberately
  # absent from this list and stays fully covered -- verified empirically: an
  # injected unused import and eval() in _router.py still report ruff:F401,
  # ruff:E402, and bandit:B307 with these exclusions active. This is unlike the
  # workflows/code/scripts/detect_facades.py entry above, where the excluded
  # path IS the real file and linting is genuinely lost.
  #
  # Generated from bin/_wrappers.yaml -- run `make bin-wrappers` to refresh.
  # `make bin-wrappers-check` (CI) fails if this block drifts from the config."""


def load_config() -> dict:
    """Load _wrappers.yaml."""
    if yaml is None:
        # Fallback: simple YAML parser for our constrained format
        return _parse_simple_yaml(CONFIG_FILE.read_text())
    return yaml.safe_load(CONFIG_FILE.read_text())


def _parse_kv_section_line(line: str, section_data: dict) -> None:
    """Parse a 'name: {key: val, ...}' line into section_data."""
    import re

    m = re.match(r"\s+(\S+):\s+\{(.+)\}", line)
    if m:
        name = m.group(1)
        fields = {}
        for kv in m.group(2).split(", "):
            k, v = kv.split(": ", 1)
            fields[k] = v.strip('"')
        section_data[name] = fields


def _parse_simple_yaml(text: str) -> dict:
    """Minimal YAML parser for our config format."""
    import re

    result: dict = {"python": {}, "bash": {}, "manual": []}
    current_section = None
    for line in text.split("\n"):
        line = line.rstrip()
        if not line or line.startswith("#"):
            continue
        if line in ("python:", "bash:", "manual:"):
            current_section = line[:-1]
            continue
        if current_section == "manual":
            m = re.match(r"\s+-\s+(\S+)", line)
            if m:
                result["manual"].append(m.group(1))
        elif current_section in ("python", "bash"):
            _parse_kv_section_line(line, result[current_section])
    return result


def _build_module_map(python_specs: dict[str, dict]) -> dict[str, str]:
    """Build {wrapper_name: module} from the python section of _wrappers.yaml."""
    return {name: spec["module"] for name, spec in python_specs.items()}


def _render_module_map(module_map: dict[str, str]) -> str:
    """Render the generated section to embed in _router.py."""
    lines = [
        _GENERATED_SECTION_HEADER,
        "# fmt: off",
        "_MODULE_MAP: dict[str, str] = {",
    ]
    for name, module in module_map.items():
        lines.append(f'    "{name}": "{module}",')
    lines += [
        "}",
        "# fmt: on",
        _GENERATED_SECTION_FOOTER,
    ]
    return "\n".join(lines)


def generate_router(module_map: dict[str, str]) -> str:
    """Render the full _router.py content with the given module map."""
    generated_section = _render_module_map(module_map)
    return _ROUTER_TEMPLATE.format(generated_section=generated_section)


def generate_bash(_name: str, spec: dict) -> str:
    """Generate bash wrapper content."""
    return BASH_TEMPLATE.format(base=spec["base"], args=spec["args"])


def _render_qlty_section(wrapper_names: list[str]) -> str:
    """Render the generated wrapper-symlink block for .qlty/qlty.toml."""
    lines = [_QLTY_SECTION_HEADER, _QLTY_SECTION_COMMENT]
    lines += [f'  "bin/{name}",' for name in sorted(wrapper_names)]
    lines.append(_QLTY_SECTION_FOOTER)
    return "\n".join(lines)


def render_qlty_config(existing: str, wrapper_names: list[str]) -> str:
    """Return qlty.toml with its generated wrapper-symlink block refreshed.

    Replaces the content between the BEGIN/END markers. If the markers are not
    present, the block is inserted just before the closing bracket of
    exclude_patterns.
    """
    section = _render_qlty_section(wrapper_names)
    lines = existing.split("\n")

    try:
        start = lines.index(_QLTY_SECTION_HEADER)
        end = lines.index(_QLTY_SECTION_FOOTER)
    except ValueError:
        return _insert_qlty_section(lines, section)

    return "\n".join(lines[:start] + section.split("\n") + lines[end + 1:])


def _insert_qlty_section(lines: list[str], section: str) -> str:
    """Insert the generated block before the close of exclude_patterns."""
    in_block = False
    for i, line in enumerate(lines):
        if line.startswith("exclude_patterns"):
            in_block = True
            continue
        if in_block and line.rstrip() == "]":
            return "\n".join(lines[:i] + section.split("\n") + lines[i:])
    raise SystemExit(
        "_gen_wrappers.py: could not locate the exclude_patterns list in "
        f"{QLTY_CONFIG}. Add the BEGIN/END wrapper-symlink markers manually."
    )


def _update_file(path: Path, content: str, check: bool) -> str:
    """Update file if content differs. Returns 'created', 'changed', or 'unchanged'."""
    if path.exists() and not path.is_symlink():
        existing = path.read_text()
        if existing == content:
            return "unchanged"
        if not check:
            path.write_text(content)
            _make_executable(path)
        return "changed"
    elif not path.exists():
        if not check:
            path.write_text(content)
            _make_executable(path)
        return "created"
    else:
        # Path is a symlink — file has a different status (handled by symlink logic)
        return "unchanged"


def _update_symlink(path: Path, target: Path, check: bool) -> str:
    """Ensure path is a symlink pointing to target (relative).

    Returns 'created', 'changed', or 'unchanged'.
    """
    rel_target = target.name  # both in same directory; use bare filename
    if path.is_symlink():
        existing_target = path.readlink()  # type: ignore[attr-defined]
        if str(existing_target) == rel_target:
            return "unchanged"
        if not check:
            path.unlink()
            path.symlink_to(rel_target)
        return "changed"
    elif path.exists():
        # Existing real file — replace with symlink
        if not check:
            path.unlink()
            path.symlink_to(rel_target)
        return "changed"
    else:
        if not check:
            path.symlink_to(rel_target)
        return "created"


def _make_executable(path: Path) -> None:
    """Add executable permission."""
    mode = path.stat().st_mode
    path.chmod(mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def _process_router(module_map: dict[str, str], check: bool, verbose: bool) -> tuple[int, int]:
    """Generate or update _router.py. Returns (changed, unchanged)."""
    content = generate_router(module_map)
    status = _update_file(ROUTER_FILE, content, check)
    if not check:
        # Always ensure exec bit is set (idempotent; may have been lost on initial write).
        _make_executable(ROUTER_FILE)
    if status in ("changed", "created"):
        label = "Updated" if status == "changed" else "Created"
        print(f"{label}: _router.py")
        return 1, 0
    if verbose:
        print("Unchanged: _router.py")
    return 0, 1


def _process_python_symlinks(
    python_specs: dict[str, dict], check: bool, verbose: bool
) -> tuple[int, int]:
    """Ensure each python wrapper is a symlink to _router.py. Returns (changed, unchanged)."""
    verbs = {
        "changed": "Would update" if check else "Updated",
        "created": "Would create" if check else "Created",
    }
    changed = 0
    unchanged = 0
    for name in python_specs:
        status = _update_symlink(BIN_DIR / name, ROUTER_FILE, check)
        verb = verbs.get(status)
        if verb is None:
            unchanged += 1
            if verbose:
                print(f"Unchanged: {name} -> _router.py")
            continue
        changed += 1
        print(f"{verb}: {name} -> _router.py")
    return changed, unchanged


def _process_qlty_config(
    python_specs: dict[str, dict], check: bool, verbose: bool
) -> tuple[int, int]:
    """Refresh the wrapper-symlink exclusions in .qlty/qlty.toml.

    Returns (changed, unchanged).
    """
    if not QLTY_CONFIG.exists():
        if verbose:
            print(f"Skipped: {QLTY_CONFIG.name} (not found)")
        return 0, 0

    existing = QLTY_CONFIG.read_text()
    content = render_qlty_config(existing, list(python_specs))
    if content == existing:
        if verbose:
            print("Unchanged: .qlty/qlty.toml")
        return 0, 1

    if not check:
        QLTY_CONFIG.write_text(content)
    print(f"{'Would update' if check else 'Updated'}: .qlty/qlty.toml")
    return 1, 0


def _process_bash_section(
    bash_specs: dict[str, dict], check: bool, verbose: bool
) -> tuple[int, int]:
    """Process bash wrappers (unchanged logic). Returns (changed, unchanged)."""
    changed = 0
    unchanged = 0
    for name, spec in bash_specs.items():
        path = BIN_DIR / name
        content = generate_bash(name, spec)
        status = _update_file(path, content, check)
        if status == "changed":
            changed += 1
            print(f"{'Would update' if check else 'Updated'}: {name}")
        elif status == "created":
            changed += 1
            print(f"{'Would create' if check else 'Created'}: {name}")
        else:
            unchanged += 1
            if verbose:
                print(f"Unchanged: {name}")
    return changed, unchanged


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Dry-run mode")
    parser.add_argument("--verbose", action="store_true", help="Show all files")
    args = parser.parse_args()

    config = load_config()
    python_specs: dict[str, dict] = config.get("python", {})
    module_map = _build_module_map(python_specs)

    c0, u0 = _process_router(module_map, args.check, args.verbose)
    c1, u1 = _process_python_symlinks(python_specs, args.check, args.verbose)
    c2, u2 = _process_bash_section(config.get("bash", {}), args.check, args.verbose)
    c3, u3 = _process_qlty_config(python_specs, args.check, args.verbose)

    changed = c0 + c1 + c2 + c3
    unchanged = u0 + u1 + u2 + u3

    print(f"\nTotal: {changed} changed, {unchanged} unchanged")
    return 1 if args.check and changed > 0 else 0


if __name__ == "__main__":
    sys.exit(main())
